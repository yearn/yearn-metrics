def test_real_postgres_atomic_coverage_and_readonly(pg):
    conn, _ = pg
    init_db(conn)
    scope = Scope(1, 'vault', 'reports')
    # A read must not prevent the writer from starting a clean atomic range.
    assert list(missing_ranges(conn, scope, 0, 9, 10)) == [(0,9)]
    def fail(writer):
        writer.execute("INSERT INTO block_timestamps VALUES (1,1,1)")
        raise ValueError('injected interruption')
    with pytest.raises(ValueError, match='injected'):
        commit_range(conn,scope,0,9,source='rpc',end_hash='hash',run_id=None,write=fail)
    assert conn.execute('SELECT count(*) FROM block_timestamps').fetchone()[0] == 0
    assert list(missing_ranges(conn, scope, 0, 9, 10)) == [(0,9)]
    commit_range(conn,scope,0,9,source='rpc',end_hash='hash',run_id=None,
                 write=lambda writer: writer.execute('INSERT INTO block_timestamps VALUES (1,1,1)').rowcount)
    assert list(missing_ranges(conn, scope, 0, 9, 10)) == []
    with closing(connect('neon', readonly=True)) as reader:
        assert reader.execute('SELECT count(*) FROM block_timestamps').fetchone()[0] == 1
        with pytest.raises(psycopg.errors.ReadOnlySqlTransaction):
            reader.execute('DELETE FROM block_timestamps')


